#!/usr/bin/env python3
"""Generate main/costean/lode_font.c: ASCII 0x20-0x7E of the firmware's own 6x8 OLED font
(main/lv_font_portfolio-6x8.c, already shipped with ESP-Miner) as plain 6x8 row masks, so the
Costean OS 128x32 renderer can draw text without LVGL and be tested on a PC."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / "main/lv_font_portfolio-6x8.c").read_text()
bm = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]+)", re.search(r"glyph_bitmap\[\] = \{(.*?)\n\};", text, re.S).group(1))]
dsc = [{k: int(v) for k, v in re.findall(r"(\w+)\s*=\s*(-?\d+)", e)}
       for e in re.findall(r"\{([^}]+)\}", re.search(r"glyph_dsc\[\] = \{(.*?)\n\};", text, re.S).group(1))]
LINE_H, BASE = 8, 1
rows_out = []
for cp in range(0x20, 0x7F):
    d = dsc[1 + cp]
    rows = [0] * 8
    if d.get("box_w", 0) and d.get("box_h", 0):
        bit = 0
        gy = LINE_H - BASE - d["box_h"] - d["ofs_y"]
        for r in range(d["box_h"]):
            for c in range(d["box_w"]):
                on = (bm[d["bitmap_index"] + bit // 8] >> (7 - bit % 8)) & 1
                bit += 1
                x, y = d["ofs_x"] + c, gy + r
                if on and 0 <= x < 6 and 0 <= y < 8:
                    rows[y] |= 0x20 >> x
    rows_out.append((cp, rows))
out = ["/* Generated by tools/gen_lode_font.py from main/lv_font_portfolio-6x8.c (ESP-Miner, GPL-3.0).",
       " * 6x8 cells, one byte per row, bit 5 = leftmost pixel. ASCII 0x20-0x7E. Do not edit. */",
       '#include "lode_oled.h"', "", "const uint8_t lode_font6x8[95][8] = {"]
for cp, rows in rows_out:
    ch = chr(cp).replace("\\", "\\\\")
    out.append("    {" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}, /* '{ch}' */" if ch not in "*/" else
               "    {" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}, /* 0x{cp:02x} */")
out.append("};")
(ROOT / "main/costean/lode_font.c").write_text("\n".join(out) + "\n")
print("wrote main/costean/lode_font.c")
